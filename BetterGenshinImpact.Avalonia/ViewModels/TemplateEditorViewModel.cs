using System.Text.RegularExpressions;
using Avalonia.Media.Imaging;
using BetterGenshinImpact.Core.Config;
using BetterGenshinImpact.Service;
using CommunityToolkit.Mvvm.ComponentModel;
using OpenCvSharp;

namespace BetterGenshinImpact.Avalonia.ViewModels;

/// <summary>
/// Linux 版模板素材制作（对照 WPF RecognitionTemplateEditorViewModel 的核心流程）：在截图上框选区域，
/// 填写 Recognition.json、Assets 根目录、对象名与模板文件名，经 Core 的 <see cref="RecognitionTemplateAssetService"/>
/// 校验并一致性写入图片与配置。高级匹配参数（掩码、二值化、搜索框扩展等）使用默认值，需要时在 Windows 版或 JSON 中调整。
/// </summary>
public sealed partial class TemplateEditorViewModel : ObservableObject, IDisposable
{
    private const int MaxRecentPathCount = 10;

    private readonly Mat _screenshot;
    private readonly RecognitionTemplateAssetService _assetService;
    private readonly DevConfig _devConfig;
    private string _lastAutoGeneratedObjectName = "";

    public TemplateEditorViewModel(Mat screenshot, RecognitionTemplateAssetService assetService, DevConfig devConfig)
    {
        _screenshot = screenshot;
        _assetService = assetService;
        _devConfig = devConfig;
        _recognitionJsonPath = devConfig.RecognitionJsonPath;
        _assetsRootPath = devConfig.RecognitionAssetsRootPath;
        Cv2.ImEncode(".png", screenshot, out var png);
        Image = new Bitmap(new MemoryStream(png));
    }

    /// <summary>截图（框选画布）</summary>
    public Bitmap Image { get; }

    public int CanvasWidth => _screenshot.Width;

    public int CanvasHeight => _screenshot.Height;

    [ObservableProperty] private string _recognitionJsonPath;

    [ObservableProperty] private string _assetsRootPath;

    [ObservableProperty] private string _objectName = "";

    [ObservableProperty] private string _templateFileName = "";

    [ObservableProperty] private double _threshold = RecognitionTemplateDraft.DefaultThreshold;

    [ObservableProperty] private int _selectionX;

    [ObservableProperty] private int _selectionY;

    [ObservableProperty] private int _selectionWidth;

    [ObservableProperty] private int _selectionHeight;

    /// <summary>保存结果或校验错误</summary>
    [ObservableProperty] private string _message = "在截图上拖动框选模板区域。";

    /// <summary>保存成功后为 true（窗口据此关闭）</summary>
    [ObservableProperty] private bool _saved;

    /// <summary>输出图片路径预览</summary>
    public string OutputImagePath => string.IsNullOrWhiteSpace(AssetsRootPath) || string.IsNullOrWhiteSpace(TemplateFileName)
        ? "" : RecognitionTemplateAssetService.GetImageOutputPath(AssetsRootPath, TemplateFileNameWithExtension);

    private string TemplateFileNameWithExtension => string.IsNullOrWhiteSpace(TemplateFileName) ? "" : ConvertToSnakeCase(TemplateFileName) + ".png";

    /// <summary>冲突确认：返回 true 覆盖（窗口弹出确认框；自测时可替换）</summary>
    public Func<string, Task<bool>>? ConfirmOverwrite { get; set; }

    partial void OnAssetsRootPathChanged(string value) => OnPropertyChanged(nameof(OutputImagePath));

    partial void OnTemplateFileNameChanged(string value)
    {
        OnPropertyChanged(nameof(OutputImagePath));
        // 与 WPF 相同：对象名为空或仍是上次自动生成的值时，随文件名生成 PascalCase 对象名
        var generated = ConvertToPascalCase(value);
        if (string.IsNullOrWhiteSpace(ObjectName) || ObjectName == _lastAutoGeneratedObjectName) ObjectName = generated;
        _lastAutoGeneratedObjectName = generated;
    }

    /// <summary>设置框选区域（画布坐标，自动裁剪到截图范围）</summary>
    public void SetSelection(double x1, double y1, double x2, double y2)
    {
        var left = (int)Math.Round(Math.Clamp(Math.Min(x1, x2), 0, CanvasWidth));
        var top = (int)Math.Round(Math.Clamp(Math.Min(y1, y2), 0, CanvasHeight));
        var right = (int)Math.Round(Math.Clamp(Math.Max(x1, x2), 0, CanvasWidth));
        var bottom = (int)Math.Round(Math.Clamp(Math.Max(y1, y2), 0, CanvasHeight));
        SelectionX = left;
        SelectionY = top;
        SelectionWidth = right - left;
        SelectionHeight = bottom - top;
    }

    /// <summary>保存模板素材（与 WPF Save 相同：Prepare 校验 → 有冲突时确认 → Commit → 记住路径）</summary>
    public async Task<bool> SaveAsync()
    {
        try
        {
            TemplateFileName = ConvertToSnakeCase(TemplateFileName);
            var plan = _assetService.Prepare(new RecognitionTemplateDraft
            {
                JsonPath = RecognitionJsonPath,
                AssetsRootPath = AssetsRootPath,
                ObjectName = ObjectName,
                TemplateFileName = TemplateFileNameWithExtension,
                Selection = new Rect(SelectionX, SelectionY, SelectionWidth, SelectionHeight),
                ReferenceWidth = CanvasWidth,
                ReferenceHeight = CanvasHeight,
                Threshold = Threshold
            });
            if (plan.Conflicts.Count > 0)
            {
                var text = $"检测到以下冲突：{Environment.NewLine}{Environment.NewLine}{string.Join(Environment.NewLine, plan.Conflicts.Select(c => $"• {c}"))}"
                           + $"{Environment.NewLine}{Environment.NewLine}是否覆盖并继续保存？";
                if (ConfirmOverwrite is null || !await ConfirmOverwrite(text))
                {
                    Message = "已取消保存。";
                    return false;
                }
            }

            _assetService.Commit(plan, _screenshot);
            Remember(plan.JsonPath, true);
            Remember(Path.GetFullPath(AssetsRootPath.Trim()), false);
            Message = $"模板素材已保存。配置：{plan.JsonPath}；图片：{plan.ImagePath}";
            Saved = true;
            return true;
        }
        catch (Exception e) when (e is ArgumentException or InvalidOperationException)
        {
            Message = e.Message;
            return false;
        }
        catch (Exception e)
        {
            Message = "保存 Recognition 模板素材失败：" + e.Message;
            return false;
        }
    }

    /// <summary>与 WPF 相同：路径放到最近记录首位，去重并截断到 10 条，赋新集合以触发配置保存</summary>
    private void Remember(string path, bool json)
    {
        if (string.IsNullOrWhiteSpace(path)) return;
        path = path.Trim();
        var history = (json ? _devConfig.RecognitionJsonPathHistory : _devConfig.RecognitionAssetsRootPathHistory)
            .Where(p => !string.Equals(p, path, StringComparison.OrdinalIgnoreCase)).Prepend(path).Take(MaxRecentPathCount).ToList();
        if (json)
        {
            _devConfig.RecognitionJsonPath = path;
            _devConfig.RecognitionJsonPathHistory = history;
        }
        else
        {
            _devConfig.RecognitionAssetsRootPath = path;
            _devConfig.RecognitionAssetsRootPathHistory = history;
        }
    }

    /// <summary>与 WPF 相同的文件名规范化（PascalCase / camelCase / 分隔符 → snake_case）</summary>
    internal static string ConvertToSnakeCase(string value)
    {
        var normalized = value.Trim();
        if (normalized.EndsWith(".png", StringComparison.OrdinalIgnoreCase)) normalized = normalized[..^4];
        normalized = Regex.Replace(normalized, @"([A-Z]+)([A-Z][a-z])", "$1_$2");
        normalized = Regex.Replace(normalized, @"([a-z0-9])([A-Z])", "$1_$2");
        normalized = Regex.Replace(normalized, @"[^\p{L}\p{Nd}]+", "_");
        normalized = Regex.Replace(normalized, @"_+", "_");
        return normalized.Trim('_').ToLowerInvariant();
    }

    private static string ConvertToPascalCase(string value)
        => string.Concat(ConvertToSnakeCase(value).Split('_', StringSplitOptions.RemoveEmptyEntries)
            .Select(word => char.ToUpperInvariant(word[0]) + word[1..]));

    public void Dispose()
    {
        Image.Dispose();
        _screenshot.Dispose();
    }
}
